namespace TerminalNinja.Controls;

/// <summary>
/// Specifies the direction in which child elements are arranged within a layout container.
/// </summary>
public enum Orientation
{
    /// <summary>
    /// Child elements are arranged horizontally (left to right).
    /// </summary>
    Horizontal,
    
    /// <summary>
    /// Child elements are arranged vertically (top to bottom).
    /// </summary>
    Vertical
}
